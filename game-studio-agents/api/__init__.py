# 统一管理与可视化指挥中枢 · 信息接口层（API）
# 版本: v0.9
# 说明: 把多 Agent 协同产生的海量事件流，降熵聚合成"关键信息 + 判断信息"，
#       以 FastAPI 提供**机器接口层**（供 AI 读取）与**可视化通用接口层**
#       （支撑人类前端），并做到"接口层与人工可视层分离"。
#
#   - /ai/*          → AI 专用机器接口：结构化、低冗余、聚合、机器友好。
#                      让 AI 每次读取都拿到干净的聚合信号，不掺杂人类偏好展示，
#                      减少无效上下文，提升决策效率。
#   - /dashboard/*   → 人类可视化通用接口：L0 总览 → L1 聚合 → L2 明细 → L3 原始，
#                      渐进式展开、可溯源，供前端页面消费。
#
# 语言: Python 3 (可运行)
